# Программа запрашивает имя и возраст пользователя

# 1. Спрашиваем имя пользователя и сохраняем в переменную 'name'
name = input("Введите ваше имя: ")

# 2. Спрашиваем возраст пользователя и сохраняем в переменную 'age'
# Функция input всегда возвращает строку.
age = input("Введите ваш возраст: ")

# 3. Выводим результаты, чтобы убедиться, что переменные сохранены
print("\n--- Результаты ---")
print(f"Имя: {name}")
print(f"Возраст: {age}")